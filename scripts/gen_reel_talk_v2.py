        HEAD,
        f"[한 줄 요약]\n{p['name'].split('(')[0]} 한 명이 셀카처럼 폰을 들고, 쿡매치의 「{ep['feature']}」 기능을 친구에게 알려 주듯 처음부터 끝까지 쉬지 않고 혼자 말하는 약 20초짜리 한 컷 영상. 중간에 끊기거나 장면이 바뀌지 않는다.",
