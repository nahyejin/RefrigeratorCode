    tpl = (ROOT / "scripts/reel_talk_v2_template.html").read_text(encoding="utf-8")
    path.write_text(tpl.replace("/*__DATA__*/null", json.dumps(data, ensure_ascii=False).replace("</", "<\\/")), encoding="utf-8")


