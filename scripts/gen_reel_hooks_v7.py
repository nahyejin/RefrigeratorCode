def clip_prompt(c, no_line=False):
    beats = "\n".join(beat_line(i + 1, b, no_line) for i, b in enumerate(c["beats"]))
    summary = c["summary"] + (" 대사 없이 표정과 동작만으로, 말소리는 없다." if no_line else "")
    return "\n\n".join([
        HEAD,
        f"[한 줄 요약]\n{summary}",
        RULES,
        f"[등장인물]\n{c['cast']}",
        f"[장소 — 처음 모습]\n{c['place']}",
        f"[장면 순서 — 위에서 아래로, 이 순서대로 한 번씩]\n{beats}",
        f"[마지막 장면]\n{c['last']}",
        TAIL,
    ])


def image_prompt(c):
    t, who, act, _, _ = c["beats"][0]
    return "\n\n".join([
        IMAGE_HEAD,
        f"[이 사진은 영상의 첫 장면]\n{c['summary']} 그 첫 순간: {who} — {act}",
        f"[등장인물]\n{c['cast']}",
        f"[장소]\n{c['place']}",
        IMAGE_STYLE,
        IMAGE_TAIL,
    ])


