def md():
    L = ["# 스레드 첫 2주 글 초안", "",
         "> `scripts/gen_threads_posts.py` 로 만든다(아티팩트 `scripts/threads_posts.html` 과 같은 내용). 기준: `store/THREADS_GUIDE.md`.",
         "> **처음 2주는 글에 앱 언급 0** (2026-10-28 사용자: 여전히 광고 계정 같다). 연재 제목도 「냉장고 앱 만드는 엄마」 → 「요알못 엄마」(쿡매치 인스타 소개와 같은 말).",
         "> **[대괄호]** = 사용자만 아는 사실. 실제 값으로 바꾸거나 그 줄을 지운다. 아이는 「딸」.", ""]
    for day, kind, photo, body, reply, note in POSTS:
        L += [f"## {day} · {kind}", f"- 사진: {photo}", "", "```", body, "```"]
        if reply:
            L.append(f"첫 답글: `{reply}`")
        if note:
            L.append(f"> {note}")
        L.append("")
    L += ["## 3주 차 이후 (앱 이야기)", ""] + [f"- **{t}** — {d}" for t, d in LATER]
    return "\n".join(L) + "\n"


def html():
    tpl = (ROOT / "scripts" / "threads_posts_template.html").read_text(encoding="utf-8")
    data = {"posts": [dict(day=d, kind=k, photo=p, body=b, reply=r, note=n) for d, k, p, b, r, n in POSTS],
            "later": [dict(t=t, d=d) for t, d in LATER], "steps": STEPS, "rules": [dict(t=t, d=d) for t, d in RULES]}
    return tpl.replace("/*DATA*/null", json.dumps(data, ensure_ascii=False))


if __name__ == "__main__":
    (ROOT / "store" / "THREADS_POSTS_W1W2.md").write_text(md(), encoding="utf-8", newline="\n")
